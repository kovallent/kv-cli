#!/usr/bin/env bash
# Print the Homebrew formula for one kv-cli release.
#
#   packaging/homebrew/formula.sh 0.7.0 SHA256SUMS > Formula/kv-cli.rb
#
# SHA256SUMS is the file the release workflow publishes beside the archives.
# The formula installs the prebuilt binary, so `brew install` needs no Rust
# toolchain and no compile. The release workflow runs this after each stable
# tag and pushes the result to github.com/kovallent/homebrew-tap.
#
# There is no `version` line: Homebrew reads it from the `/download/vX.Y.Z/`
# URLs, and `brew audit --strict` rejects a version it can already scan.
set -euo pipefail

version="${1:?usage: formula.sh VERSION SHA256SUMS}"
sums="${2:?usage: formula.sh VERSION SHA256SUMS}"
base="https://github.com/kovallent/kv-cli/releases/download/v${version}"

sha() {
  local archive="kv-cli-$1.tar.gz" found
  found=$(awk -v f="$archive" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  if [[ ! "$found" =~ ^[0-9a-f]{64}$ ]]; then
    echo "formula.sh: no checksum for $archive in $sums" >&2
    exit 1
  fi
  echo "$found"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-gnu)
linux_intel=$(sha x86_64-unknown-linux-gnu)

cat <<RUBY
# Generated by packaging/homebrew/formula.sh in kovallent/kv-cli. Edits here
# are overwritten by the next release.
class KvCli < Formula
  desc "Local contract guardrails for Python data pipelines"
  homepage "https://github.com/kovallent/kv-cli"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/kv-cli-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/kv-cli-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/kv-cli-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/kv-cli-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${linux_intel}"
    end
  end

  def install
    bin.install "kv-cli"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kv-cli --version")
    (testpath/"pipeline.py").write <<~PY
      def deploy_orders(name):
          return name
    PY
    output = shell_output("#{bin}/kv-cli audit pipeline.py --no-color", 1)
    assert_match "KV001", output
  end
end
RUBY
